"""Download the demo evidence photos listed in ui/evidence/manifest.json.

The photos are openly licensed images from Wikimedia Commons (real car-damage photos uploaded before 2022,
and AI-generated images for the "fake photo" claims). They are NOT committed to git (plan.md: never commit
images); this script fetches them and writes ui/evidence/evidence.js, which the console loads to show each
photo with its attribution, and which maps the gateway's evidence IDs (EV-<first 8 hex of sha256>) to files.

  python demo/fetch_evidence.py            # download missing files, rebuild evidence.js
  python demo/fetch_evidence.py --force    # re-download everything

Team-supplied images (manifest entries with "local": true) can't be downloaded. Save them as
ui/evidence/<key>_source.jpg (or .png); the script copies them to <key>.jpg, cropping first if the entry
says so ("crop": "right_half" keeps the right half of a before/after pair; needs Pillow). Until a local
image is present, that claim simply shows no photo.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
EVIDENCE = REPO / "ui" / "evidence"
UA = "AegisHackathonDemo/0.1 (https://github.com/Berketunc/Aegis; demo evidence fetch)"
WIDTH = 1024


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def commons_thumb(title: str) -> str:
    q = urllib.parse.urlencode({"action": "query", "format": "json", "titles": title, "prop": "imageinfo",
                                "iiprop": "url", "iiurlwidth": WIDTH})
    pages = json.loads(get("https://commons.wikimedia.org/w/api.php?" + q))["query"]["pages"]
    info = next(iter(pages.values()))["imageinfo"][0]
    return info.get("thumburl") or info["url"]


def prepare_local(src: Path, dst: Path, crop: str | None) -> Path:
    try:
        from PIL import Image
    except ImportError:
        if crop:
            print(f"  Pillow not installed: using {src.name} uncropped")
        dst.write_bytes(src.read_bytes())
        return dst
    im = Image.open(src).convert("RGB")
    if crop == "right_half":
        im = im.crop((im.width // 2, 0, im.width, im.height))
    im.save(dst, "JPEG", quality=92)
    return dst


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    manifest = json.loads((EVIDENCE / "manifest.json").read_text(encoding="utf-8"))
    out = {}
    for key, m in manifest["photos"].items():
        existing = sorted(EVIDENCE.glob(f"{key}.*"))
        existing = [p for p in existing if p.suffix.lower() in (".jpg", ".jpeg", ".png")]
        if m.get("local"):
            src = next((p for p in sorted(EVIDENCE.glob(f"{key}_source.*")) if p.suffix.lower() in (".jpg", ".jpeg", ".png", ".webp")), None)
            if src and (args.force or not existing or existing[0].stat().st_mtime < src.stat().st_mtime):
                for p in existing:
                    p.unlink()
                path = prepare_local(src, EVIDENCE / f"{key}.jpg", m.get("crop"))
                print(f"{key}: {src.name} -> {path.name}" + (f" (cropped {m['crop']})" if m.get("crop") else ""))
            elif existing:
                path = existing[0]
            else:
                print(f"{key}: team-supplied image missing (save it as ui/evidence/{key}_source.jpg)")
                continue
        elif existing and not args.force:
            path = existing[0]
        else:
            url = m.get("download_url") or commons_thumb(m["title"])
            data = get(url)
            ext = ".png" if data[:8] == b"\x89PNG\r\n\x1a\n" else ".jpg"
            for p in existing:
                p.unlink()
            path = EVIDENCE / f"{key}{ext}"
            path.write_bytes(data)
            print(f"{key}: {m['title']} -> {path.name} ({len(data) // 1024} KB)")
            time.sleep(0.5)  # be polite to Wikimedia
        sha = hashlib.sha256(path.read_bytes()).hexdigest()
        out[key] = {**{k: m[k] for k in ("kind", "title", "page_url", "author", "license", "license_url", "source", "shows", "uploaded") if k in m},
                    "file": path.name, "sha256": sha, "evidence_id": "EV-" + sha[:8].upper()}
    js = ("/* Generated by demo/fetch_evidence.py from manifest.json. Do not edit. */\n"
          "window.AEGIS_EVIDENCE = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n")
    (EVIDENCE / "evidence.js").write_text(js, encoding="utf-8")
    print(f"\n{len(out)} photos ready; wrote ui/evidence/evidence.js")
    return 0


if __name__ == "__main__":
    sys.exit(main())
