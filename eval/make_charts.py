"""Two charts for the video (plan.md §3, Person A, 21:30-03:00), 1920x1080 PNG.

1. eval/charts/caught_at_red.png    share of AI-made test photos the final model sends to RED, by kind
2. eval/charts/honest_flagged.png   share of honest (real) test photos sent to RED, first vs final model,
                                    on original, JPEG-q50 and half-size copies

Values are read from eval/runs/*_eval.json, so the charts always match eval/results.md.
Palette: reference categorical slots 1-2 (blue, orange), validated with the dataviz validator.

Usage:  uv run --no-project --with matplotlib python eval/make_charts.py
"""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

RUNS = Path("eval/runs")
OUT = Path("eval/charts")
FINAL, FIRST = "det-r18-v4_mean_eval.json", "det-r18-v1_mean_eval.json"

SURFACE, INK, INK2, MUTED, GRID, AXIS = "#fcfcfb", "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7"
BLUE, ORANGE = "#2a78d6", "#eb6834"  # categorical slots 1 and 2

plt.rcParams.update({
    "font.family": ["Helvetica Neue", "Helvetica", "Arial", "DejaVu Sans"],
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "text.color": INK, "axes.labelcolor": INK2, "xtick.color": MUTED, "ytick.color": INK,
})


def block(res, name):
    return next(b for b in res["blocks"] if b["name"] == name)


def frame(ax):
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(AXIS)
    ax.tick_params(length=0)
    ax.grid(axis="x", color=GRID, linewidth=1)
    ax.set_axisbelow(True)


def titles(fig, title, subtitle):
    fig.text(0.06, 0.92, title, fontsize=34, fontweight="bold", color=INK, ha="left")
    fig.text(0.06, 0.865, subtitle, fontsize=20, color=INK2, ha="left")


def caught_at_red(final):
    rows = [  # (label, block, key)
        ("Fully generated scene (SDXL)", "sdxl_only", "tpr_at_red"),
        ("Real photo regenerated by AI", "regenerated_only", "tpr_at_red"),
        ("Generator never seen in training (FLUX)", "flux_holdout", "tpr_at_red"),
        ("Small AI edit on a real photo", "inflation_only", "tpr_at_red"),
    ]
    vals = [100 * block(final, b)[k] for _, b, k in rows]
    fpr = 100 * block(final, "real_damage_only")["fpr_at_red"]
    fig, ax = plt.subplots(figsize=(19.2, 10.8), dpi=100)
    fig.subplots_adjust(left=0.36, right=0.93, top=0.78, bottom=0.12)
    y = list(range(len(rows)))[::-1]
    ax.barh(y, vals, height=0.42, color=BLUE)
    for yi, v in zip(y, vals):
        ax.text(v + 1.2, yi, f"{v:.0f}%", va="center", fontsize=24, fontweight="bold", color=INK)
    ax.set_yticks(y, [r[0] for r in rows], fontsize=22)
    ax.set_xlim(0, 100)
    ax.set_xticks([0, 25, 50, 75, 100], ["0%", "25%", "50%", "75%", "100%"], fontsize=16)
    frame(ax)
    titles(fig, "What the detector sends to a human investigator",
           f"Share of AI-made test photos scored RED. Honest damage photos scored RED: {fpr:.1f}%.")
    fig.text(0.06, 0.04, "Test split, model det-r18-v4, RED threshold set so ≤1% of real validation photos cross it.",
             fontsize=15, color=MUTED, ha="left")
    fig.savefig(OUT / "caught_at_red.png")
    plt.close(fig)


def honest_flagged(first, final):
    conds = [("Original photo", "real_damage_only"), ("Recompressed (JPEG quality 50)", "compression_jpeg_q50"),
             ("Shrunk to half size", "compression_resize_half")]
    v1 = [100 * block(first, b)["fpr_at_red"] for _, b in conds]
    v4 = [100 * block(final, b)["fpr_at_red"] for _, b in conds]
    fig, ax = plt.subplots(figsize=(19.2, 10.8), dpi=100)
    fig.subplots_adjust(left=0.30, right=0.93, top=0.74, bottom=0.12)
    h = 0.32
    ys = list(range(len(conds)))[::-1]
    for yi, a, b in zip(ys, v1, v4):
        ax.barh(yi + h / 2 + 0.01, a, height=h, color=ORANGE)  # 2px-ish surface gap between the pair
        ax.barh(yi - h / 2 - 0.01, b, height=h, color=BLUE)
        ax.text(a + 0.8, yi + h / 2 + 0.01, f"{a:.1f}%", va="center", fontsize=20, color=INK)
        ax.text(b + 0.8, yi - h / 2 - 0.01, f"{b:.1f}%", va="center", fontsize=20, fontweight="bold", color=INK)
    ax.set_yticks(ys, [c[0] for c in conds], fontsize=22)
    ax.set_xlim(0, 100)
    ax.set_xticks([0, 25, 50, 75, 100], ["0%", "25%", "50%", "75%", "100%"], fontsize=16)
    frame(ax)
    titles(fig, "Honest photos wrongly sent to RED",
           "Real test photos scored RED after everyday handling. Lower is better.")
    # legend: always present for 2 series, above the plot
    fig.text(0.30, 0.79, "■", color=ORANGE, fontsize=22, va="center")
    fig.text(0.318, 0.79, "First model", color=INK2, fontsize=20, va="center")
    fig.text(0.43, 0.79, "■", color=BLUE, fontsize=22, va="center")
    fig.text(0.448, 0.79, "Final model (trained on degraded copies, never upscales)", color=INK2, fontsize=20, va="center")
    fig.text(0.06, 0.04, "Test split; first model det-r18-v1, final model det-r18-v4; each at its own RED threshold.",
             fontsize=15, color=MUTED, ha="left")
    fig.savefig(OUT / "honest_flagged.png")
    plt.close(fig)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    final = json.loads((RUNS / FINAL).read_text())
    first = json.loads((RUNS / FIRST).read_text())
    caught_at_red(final)
    honest_flagged(first, final)
    print("wrote", *sorted(str(p) for p in OUT.glob("*.png")))
