"""Claims transaction CLMI: a CICS-pattern gateway.

Validate -> idempotency check -> privacy rules -> risk service (300 ms) -> CLMIPOL rule
-> one SQLite transaction (SYNCPOINT) -> response -> async Granite job for AMBER/RED.
CICS is emulated here; the production design is in txn/README.md.
"""
from __future__ import annotations

import asyncio
import logging
import re
import time
import uuid
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Any

import httpx
from fastapi import BackgroundTasks, FastAPI, File, Header, HTTPException, Request, UploadFile
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from privacy import build_egress, redact

from . import db, granite, risk_client
from .config import Settings
from .policy import PolicyInput, evaluate, resolve_engine

log = logging.getLogger("clmi")
TXN = "CLMI"
_MAGIC = {b"\xff\xd8\xff": "image/jpeg", b"\x89PNG\r\n\x1a\n": "image/png"}


class Claimant(BaseModel):
    name: str = Field(min_length=1, max_length=200)
    email: str | None = Field(default=None, max_length=200)
    phone: str | None = Field(default=None, max_length=40)


class Incident(BaseModel):
    date: str = Field(max_length=20)
    description: str = Field(max_length=4000)


class EvidenceRef(BaseModel):
    evidence_id: str = Field(max_length=100)


class ClaimIn(BaseModel):
    idempotency_key: str | None = Field(default=None, max_length=64,
                                        description="UUID generated by the UI when the form opens")
    policy_number: str = Field(max_length=40)
    claimant: Claimant
    incident: Incident
    evidence: list[EvidenceRef] = Field(max_length=8)
    damage_category: str | None = Field(default=None, max_length=40)


def _redact_claim(claim: ClaimIn, key: bytes) -> tuple[dict[str, Any], list[tuple[str, str, str]]]:
    """Pseudonymised record for storage and display. The vault keeps token -> value for authorised re-linking."""
    gaz = {"name": claim.claimant.name, "email": claim.claimant.email or "",
           "phone": claim.claimant.phone or "", "policy_number": claim.policy_number}
    vault: list[tuple[str, str, str]] = []

    def tok(field: str, value: str | None) -> str | None:
        if not value:
            return None
        text, found = redact(value, key, {field: value})
        vault.extend((f.token, f.kind, f.value) for f in found)
        return text

    desc, found = redact(claim.incident.description, key, gaz)
    vault.extend((f.token, f.kind, f.value) for f in found)
    damage_category = claim.damage_category
    if damage_category:
        damage_category, found = redact(damage_category, key, gaz)
        vault.extend((f.token, f.kind, f.value) for f in found)
    record = {
        "policy_number": tok("policy_number", claim.policy_number),
        "claimant": {"name": tok("name", claim.claimant.name), "email": tok("email", claim.claimant.email),
                     "phone": tok("phone", claim.claimant.phone)},
        "incident": {"date": claim.incident.date, "description": desc},
        "evidence": [e.evidence_id for e in claim.evidence],
        "damage_category": damage_category,
    }
    return record, vault


def _relink(obj: Any, mapping: dict[str, str]) -> Any:
    if isinstance(obj, dict):
        return {k: _relink(v, mapping) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_relink(v, mapping) for v in obj]
    if isinstance(obj, str):
        return re.sub(r"\b[A-Z]+_[0-9a-f]{8}\b", lambda m: mapping.get(m.group(), m.group()), obj)
    return obj


def create_app(settings: Settings | None = None, transport: httpx.AsyncBaseTransport | None = None) -> FastAPI:
    settings = settings or Settings()

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        app.state.conn = db.connect(settings.db_path)
        app.state.http = httpx.AsyncClient(transport=transport)
        app.state.claim_locks = {}
        log.info("CLMI up: policy engine=%s", resolve_engine(settings.policy_engine, settings.clmipol_bin))
        yield
        await app.state.http.aclose()
        app.state.conn.close()

    app = FastAPI(title="Claims transaction CLMI", lifespan=lifespan)
    app.state.settings = settings

    @asynccontextmanager
    async def claim_guard(key: str):
        # One-worker deployment: dictionary/refcounts are updated without awaits,
        # so concurrent requests sharing an idempotency key queue before scoring.
        # Entries survive while a holder or waiter exists and are then removed.
        entries = app.state.claim_locks
        entry = entries.get(key)
        if entry is None:
            entry = entries[key] = {"lock": asyncio.Lock(), "users": 0}
        entry["users"] += 1
        try:
            async with entry["lock"]:
                yield
        finally:
            entry["users"] -= 1
            if entry["users"] == 0:
                entries.pop(key, None)

    @app.get("/health")
    async def health() -> dict[str, Any]:
        try:
            tv = settings.load_thresholds().version
        except (OSError, ValueError, KeyError):
            tv = "unavailable"
        return {"status": "ok", "txn": TXN, "thresholds_version": tv,
                "policy_engine": resolve_engine(settings.policy_engine, settings.clmipol_bin)}

    @app.post("/evidence")
    async def upload_evidence(request: Request, file: UploadFile = File(...)) -> dict[str, Any]:
        cl = request.headers.get("content-length")
        if cl and cl.isdigit() and int(cl) > settings.max_upload_bytes + 64 * 1024:
            raise HTTPException(413, "file too large")
        content = await file.read(settings.max_upload_bytes + 1)
        if len(content) > settings.max_upload_bytes:
            raise HTTPException(413, "file too large")
        if not content:
            raise HTTPException(400, "empty file")
        ctype = next((t for m, t in _MAGIC.items() if content.startswith(m)), None)
        if ctype is None:
            raise HTTPException(415, "only JPEG or PNG photos are accepted")
        try:
            res = await risk_client.upload_evidence(app.state.http, settings.risk_url, settings.risk_secret,
                                                    file.filename or "photo", content, ctype)
            evidence_id = str(res["evidence_id"])
        except (httpx.HTTPError, ValueError, KeyError) as e:
            log.warning("evidence upload failed: %s", type(e).__name__)
            raise HTTPException(503, "evidence store unavailable, please retry") from e
        db.add_evidence(app.state.conn, evidence_id, res.get("sha256"), len(content))
        return {"evidence_id": evidence_id, "sha256": res.get("sha256")}

    @app.post("/claims")
    async def submit_claim(claim: ClaimIn, background: BackgroundTasks,
                           idempotency_key: str | None = Header(default=None)) -> dict[str, Any]:
        t0 = time.perf_counter()
        key = claim.idempotency_key or idempotency_key or str(uuid.uuid4())
        async with claim_guard(key):
            return await submit_claim_locked(claim, background, key, t0)

    async def submit_claim_locked(claim: ClaimIn, background: BackgroundTasks,
                                  key: str, t0: float) -> dict[str, Any]:
        conn = app.state.conn

        # 1. Validate before anything is scored or committed.
        if not claim.evidence:
            raise HTTPException(400, "at least one photo is required")
        missing = db.unknown_evidence(conn, [e.evidence_id for e in claim.evidence])
        if missing:
            raise HTTPException(400, f"unknown evidence_id: {', '.join(missing)}")

        # 2. Idempotency: the same claim submitted twice gets the same answer, without re-scoring.
        prior = db.find_by_key(conn, key)
        if prior:
            db.record_replay(conn, prior["claim_id"], key)
            return {**prior, "idempotency_key": key, "replayed": True,
                    "replay_timings_ms": {"total": round((time.perf_counter() - t0) * 1000, 1)}}

        claim_id = db.reserve_claim_id(conn)

        # 3. Privacy rules: only pseudonymised data is stored, scored or sent anywhere.
        redacted, vault = _redact_claim(claim, settings.hmac_key)

        # 4. Risk service, hard timeout. None => fail safe.
        t_risk = time.perf_counter()
        risk = await risk_client.score(app.state.http, settings.risk_url, settings.risk_secret,
                                       settings.risk_timeout_ms, claim_id, redacted["incident"]["description"],
                                       [{"evidence_id": e} for e in redacted["evidence"]],
                                       privacy_context={"claim_id": claim_id, "damage_category": redacted["damage_category"]},
                                       policy_token=redacted["policy_number"])
        risk_ms = (time.perf_counter() - t_risk) * 1000

        # 5. Decision rule.
        t_pol = time.perf_counter()
        sig = risk.signals if risk else None
        try:
            th = settings.load_thresholds()
            thresholds_version, tau_red, tau_amber = th.version, th.tau_red, th.tau_amber
            thresholds_ok = True
        except (OSError, ValueError, KeyError):
            log.error("thresholds config unreadable: %s", settings.thresholds_path)
            thresholds_version, tau_red, tau_amber, thresholds_ok = "unavailable", 0.0, 0.0, False
        if thresholds_ok:
            threshold_mismatch = bool(risk and risk.thresholds_version is not None
                                      and risk.thresholds_version != thresholds_version)
            if threshold_mismatch:
                risk, sig = None, None
                log.warning("risk threshold version differs for %s", claim_id)
            pin = PolicyInput(
                ai_score=sig.ai_score if sig else 0.0, tau_red=tau_red, tau_amber=tau_amber,
                duplicate=bool(sig and sig.duplicate_of and sig.duplicate_of != claim_id),
                software_tag=bool(sig and sig.metadata.software_tag), risk_ok=risk is not None)
            result = await asyncio.to_thread(evaluate, pin, settings.policy_engine, settings.clmipol_bin)
            band, reasons, engine = result.band, list(result.reasons), result.engine
            if threshold_mismatch:
                reasons.append("THRESHOLDS_VERSION_MISMATCH")
        else:
            band, reasons, engine = "AMBER", ["THRESHOLDS_UNAVAILABLE"], "none"
        if sig:  # informational only: never changes the band
            info = []
            if sig.metadata.exif_present is False:
                info.append("INFO_EXIF_MISSING")
            if sig.metadata.c2pa_manifest:
                info.append("INFO_C2PA_MANIFEST_PRESENT")
            reasons = info if reasons == ["NONE"] and info else reasons + info
        policy_ms = (time.perf_counter() - t_pol) * 1000

        signals = sig.model_dump() if sig else None
        egress_payload, egress_dropped = build_egress({
            "description_redacted": redacted["incident"]["description"],
            "damage_category": redacted["damage_category"],
            "band": band,
            "ai_score": round(sig.ai_score, 4) if sig else None,
            "exif_present": sig.metadata.exif_present if sig else None,
            "software_tag_present": bool(sig.metadata.software_tag) if sig else None,
            "c2pa_manifest": sig.metadata.c2pa_manifest if sig else None,
            "duplicate_detected": "DUPLICATE_PHOTO" in reasons,
        })
        decision = {"claim_id": claim_id, "band": band, "reasons": reasons,
                    "model_version": risk.model_version if risk else None,
                    "thresholds_version": thresholds_version, "policy_engine": engine}

        # 6. SYNCPOINT. Stored/journal timings explicitly stop before commit.
        # The HTTP response adds measured commit and complete request latency.
        total_ms = (time.perf_counter() - t0) * 1000
        decision["timings_ms"] = {"gateway": round(total_ms - risk_ms - policy_ms, 1), "risk": round(risk_ms, 1),
                                  "policy": round(policy_ms, 1), "precommit_total": round(total_ms, 1)}
        if risk and risk.timings_ms:
            decision["timings_ms"]["risk_detail"] = risk.timings_ms
        commit_start = time.perf_counter()
        try:
            db.commit_decision(conn, claim_id=claim_id, idem_key=key, redacted=redacted, vault=vault,
                               decision=decision, signals=signals, egress_id=f"EG-{claim_id[4:]}",
                               egress_payload=egress_payload, egress_dropped=egress_dropped)
        except db.DuplicateKey:
            prior = db.find_by_key(conn, key)
            db.record_replay(conn, prior["claim_id"], key)
            return {**prior, "idempotency_key": key, "replayed": True,
                    "replay_timings_ms": {"total": round((time.perf_counter() - t0) * 1000, 1)}}
        response_timings = {**decision["timings_ms"],
                            "commit": round((time.perf_counter() - commit_start) * 1000, 1),
                            "total": round((time.perf_counter() - t0) * 1000, 1)}

        # 8. Granite after the decision, only when a signal crossed AMBER.
        if settings.granite_url and band in ("AMBER", "RED") and risk is not None:
            background.add_task(_granite_job, claim_id, redacted, decision, signals or {})
        return {**decision, "timings_ms": response_timings, "idempotency_key": key, "replayed": False}

    async def _granite_job(claim_id: str, redacted: dict[str, Any], decision: dict[str, Any],
                           signals: dict[str, Any]) -> None:
        out = await granite.run_job(client=app.state.http, granite_url=settings.granite_url,
                                    timeout_s=settings.granite_timeout_s, prompts_dir=settings.prompts_dir,
                                    shared_secret=settings.risk_secret,
                                    key=settings.hmac_key, redacted=redacted, decision=decision, signals=signals)
        db.save_note(app.state.conn, claim_id, out["status"], out["note"], out["pii_added"], out["vault"],
                     out["redacted"])

    @app.get("/claims/{claim_id}")
    async def get_claim(claim_id: str) -> dict[str, Any]:
        decision = db.get_decision(app.state.conn, claim_id)
        if not decision:
            raise HTTPException(404, "no such claim")
        note = db.get_note(app.state.conn, claim_id)
        if note is None:
            note = {"status": "pending" if decision["band"] != "GREEN" and settings.granite_url else "not_requested",
                    "note": None}
        return {**decision, "adjuster_note": note}

    @app.get("/claims/{claim_id}/views")
    async def views(claim_id: str, x_role: str = Header(default="adjuster")) -> dict[str, Any]:
        """'Who sees what': adjusters get the pseudonymised record; only an authorised role re-links identity."""
        conn = app.state.conn
        record = db.get_claim(conn, claim_id)
        if record is None:
            raise HTTPException(404, "no such claim")
        out: dict[str, Any] = {"claim_id": claim_id, "role": x_role, "pseudonymised": record,
                               "egress": db.get_egress(conn, claim_id), "original": None}
        if x_role == "authorised":
            tokens = sorted(set(re.findall(r"\b[A-Z]+_[0-9a-f]{8}\b", str(record))))
            out["original"] = _relink(record, db.vault_lookup(conn, tokens))
            db.journal(conn, claim_id, "VIEW_ORIGINAL", {"role": x_role})
        return out

    @app.get("/journal")
    async def journal(claim_id: str | None = None, limit: int = 200) -> list[dict[str, Any]]:
        return db.read_journal(app.state.conn, claim_id, min(limit, 1000))

    ui = Path(settings.ui_dir)
    if ui.is_dir():
        app.mount("/", StaticFiles(directory=ui, html=True), name="ui")
    return app


app = create_app()
